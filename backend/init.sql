-- Trigger function to generate demi application reference number
CREATE OR REPLACE FUNCTION generate_demi_application_reference()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- Fill only when the app did not provide one
    IF NEW."Reference" IS NULL OR btrim(NEW."Reference") = '' THEN
        SELECT
            'APP-' || TO_CHAR(COALESCE(NEW."DateSubmitted", CURRENT_TIMESTAMP), 'YYYYMMDD')
            || '-' || COALESCE(s."StudentNumber", NEW."StudentID"::TEXT)
            || '-' || COALESCE(m."ModuleCode", NEW."ListingID"::TEXT)
        INTO NEW."Reference"
        FROM (VALUES (NEW."StudentID", NEW."ListingID")) AS input("StudentID", "ListingID")
        LEFT JOIN "STUDENT" s
          ON s."StudentID" = input."StudentID"
        LEFT JOIN "DEMI_LISTING" l
          ON l."ListingID" = input."ListingID"
        LEFT JOIN "NWU_MODULE" m
          ON m."ModuleID" = l."ModuleID";
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_generate_demi_application_reference
BEFORE INSERT OR UPDATE OF "StudentID", "ListingID", "DateSubmitted", "Reference"
ON "DEMI_APPLICATION"
FOR EACH ROW
EXECUTE FUNCTION generate_demi_application_reference();

